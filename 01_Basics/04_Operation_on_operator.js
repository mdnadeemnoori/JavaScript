let operand1 = 30
//postfix operation
const op1 = operand1++
console.log(`operand1:${operand1}, op1:${op1}`);
//infix or prefix operation
let operand2 = 35
const op2 = ++operand2
console.log(`operand2:${operand2}, op2:${op2}`);
//unary negation operator
let operand3 = 36
const op3 = -operand3
console.log(op3)